WORD = re.compile(r"[a-z']+")


def lang_of(text):
    words = WORD.findall(text.lower())
    return "tl" if any(w in TL for w in words) else "en"


def main():
    owner = json.load(open(OWNER, encoding="utf-8"))["chat_lines"]
    extra = json.load(open(EXTRA, encoding="utf-8"))["chat_lines"]
    merged = {}
    for src in (owner, extra):
        for cat, lines in src.items():
            out = merged.setdefault(cat, [])
            seen = {l.lower() for l in out}
            for line in lines:
                line = line.strip()
                if line and line.lower() not in seen:
                    out.append(line)
                    seen.add(line.lower())
    total = sum(len(v) for v in merged.values())
    os.makedirs(os.path.dirname(OUT_JSON), exist_ok=True)
    meta = {
        "description": "Bot chat: the owner's lines (bot_trashtalk_chat_lines.json) and the lines added in run "
                       "2026-10-18 h (tools/bot_chat_extra.json), merged by tools/bot_chat.py.",
        "total_lines": total,
        "category_breakdown": {k: len(v) for k, v in merged.items()},
    }
    with open(OUT_JSON, "w", encoding="utf-8", newline="\n") as f:
        json.dump({"metadata": meta, "chat_lines": merged}, f, ensure_ascii=False, indent=2)
        f.write("\n")
    gd = ["class_name BotChatLines", "extends RefCounted",
          "## Bot chat lines, generated by tools/bot_chat.py from bot_trashtalk_chat_lines.json (the owner's) and",
          "## tools/bot_chat_extra.json. Do not edit by hand: edit those files and run the tool. Each line is",
          "## [text, \"tl\" (Filipino or Taglish) or \"en\"]. %d lines." % total, "", "const LINES := {"]
    for cat, lines in merged.items():
        gd.append("\t%s: [" % json.dumps(cat))
        for line in lines:
            gd.append("\t\t[%s, \"%s\"]," % (json.dumps(line, ensure_ascii=False), lang_of(line)))
        gd.append("\t],")
    gd.append("}")
    with open(OUT_GD, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(gd) + "\n")
    for k, v in merged.items():
        tl = sum(1 for l in v if lang_of(l) == "tl")
        print("  %-40s %4d  (%d Filipino/Taglish)" % (k, len(v), tl))
    print("total %d lines" % total)


if __name__ == "__main__":
    main()
