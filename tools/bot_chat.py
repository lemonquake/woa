"""Bot chat lines (run 2026-10-18 h): merges the owner's bot_trashtalk_chat_lines.json with tools/bot_chat_extra.json
into assets/data/bot_chat.json (the full list, for reading and editing) and src/sim/bot_chat_lines.gd (the same lines
as GDScript constants: the simulation picks lines deterministically, multiplayer included, and a constant ships in the
export without an import step).

    python tools/bot_chat.py            # rebuild both, print the count per category

Each line is tagged with its language: "tl" (Filipino or Taglish: any common Filipino word) or "en". A bot's voice
(SimBotChat) prefers one or mixes both.
"""
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OWNER = os.path.join(ROOT, "bot_trashtalk_chat_lines.json")
EXTRA = os.path.join(ROOT, "tools", "bot_chat_extra.json")
OUT_JSON = os.path.join(ROOT, "assets", "data", "bot_chat.json")
OUT_GD = os.path.join(ROOT, "src", "sim", "bot_chat_lines.gd")

# common Filipino words and Taglish markers (whole words)
